import yaml
import os

# Configuration
INPUT_FILE = "Project/Tools/schema.yaml"
CPP_OUTPUT = "Project/Schema/Schema.h"
HLSL_OUTPUT = "Project/Assets/Shader/Schema/Schema.hlsli"
CS_OUTPUT = "SubProjects/ONEngine.Scripting/Generated/Schema.cs"

TYPE_MAP_CPP = {
    "float4x4": "Engine::Math::Matrix4x4",
    "float4": "Engine::Math::Vector4",
    "float3": "Engine::Math::Vector3",
    "float2": "Engine::Math::Vector2",
    "float": "float",
    "uint32": "uint32_t",
    "uint64": "uint64_t",
}

TYPE_MAP_HLSL = {
    "float4x4": "float4x4",
    "float4": "float4",
    "float3": "float3",
    "float2": "float2",
    "float": "float",
    "uint32": "uint",
    "uint64": "uint2", 
}

TYPE_MAP_CS = {
    "float4x4": "Matrix4x4",
    "float4": "Vector4",
    "float3": "Vector3",
    "float2": "Vector2",
    "float": "float",
    "uint32": "uint",
    "uint64": "ulong",
}

TYPE_SIZES = {
    "float4x4": 64,
    "float4": 16,
    "float3": 12,
    "float2": 8,
    "float": 4,
    "uint32": 4,
    "uint64": 8,
    "string": 256,
}

def generate():
    if not os.path.exists(INPUT_FILE):
        print("Error: {} not found.".format(INPUT_FILE))
        return

    with open(INPUT_FILE, "r") as f:
        schema = yaml.safe_load(f)

    cpp_content = "#pragma once\n#include \"Engine/Core/Math/Math.h\"\n#include <cstdint>\n\nnamespace Engine::GeneratedSchema {\n\n"
    ecs_content = "\n} // namespace Engine::GeneratedSchema\n\nnamespace Engine::ECS {\n\n"
    hlsl_content = "// Generated by codegen.py\n\n"
    cs_content = "using System.Runtime.InteropServices;\nusing ONEngine.Scripting.Math;\n\nnamespace ONEngine.Scripting.Generated\n{\n"

    for type_name, info in schema.get("types", {}).items():
        type_category = info.get("type")
        is_comp = type_category == "Component"
        fields = info.get("fields", [])
        
        cpp_struct_body = ""
        hlsl_struct_body = ""
        cs_struct_body = ""
        
        current_offset = 0
        pad_index = 0
        
        for field in fields:
            f_name = field["name"]
            f_type = field["type"]
            f_size = TYPE_SIZES[f_type]
            
            # Alignment check (except for strings which are large and usually custom-aligned)
            if f_type != "string":
                remaining_in_chunk = 16 - (current_offset % 16)
                if f_size > remaining_in_chunk and remaining_in_chunk < 16:
                    pad_size = remaining_in_chunk
                    cpp_struct_body += "    uint8_t _pad{}[{}];\n".format(pad_index, pad_size)
                    hlsl_struct_body += "    uint _pad{}[{}];\n".format(pad_index, pad_size // 4)
                    cs_struct_body += "        private unsafe fixed byte _pad{}[{}];\n".format(pad_index, pad_size)
                    pad_index += 1
                    current_offset += pad_size

            if f_type == "string":
                cpp_struct_body += "    char {}[256];\n".format(f_name)
                hlsl_struct_body += "    uint {}[64];\n".format(f_name)
                cs_struct_body += "        public unsafe fixed byte {}[256];\n".format(f_name)
            else:
                f_count = field.get("count", 1)
                if f_count > 1:
                    cpp_struct_body += "    {} {}[{}];\n".format(TYPE_MAP_CPP[f_type], f_name, f_count)
                    hlsl_struct_body += "    {} {}[{}];\n".format(TYPE_MAP_HLSL[f_type], f_name, f_count)
                    cs_struct_body += "        public unsafe fixed {} {}[{}];\n".format(TYPE_MAP_CS[f_type], f_name, f_count)
                    f_size *= f_count
                else:
                    cpp_struct_body += "    {} {};\n".format(TYPE_MAP_CPP[f_type], f_name)
                    hlsl_struct_body += "    {} {};\n".format(TYPE_MAP_HLSL[f_type], f_name)
                    cs_struct_body += "        public {} {};\n".format(TYPE_MAP_CS[f_type], f_name)
            
            current_offset += f_size

        # Round up to 16 bytes
        if current_offset % 16 != 0:
            pad_size = 16 - (current_offset % 16)
            cpp_struct_body += "    uint8_t _final_pad{}[{}];\n".format(pad_index, pad_size)
            hlsl_struct_body += "    uint _final_pad{}[{}];\n".format(pad_index, pad_size // 4)
            cs_struct_body += "        private unsafe fixed byte _final_pad{}[{}];\n".format(pad_index, pad_size)
            current_offset += pad_size

        struct_decl_cpp = "struct {} {{\n{}}};\n\n".format(type_name, cpp_struct_body)
        struct_decl_hlsl = "struct {} {{\n{}}};\n\n".format(type_name, hlsl_struct_body)
        struct_decl_cs = "    [StructLayout(LayoutKind.Sequential)]\n    public struct {}\n    {{\n{}{}    }}\n\n".format(type_name, "", cs_struct_body)
        
        if is_comp:
            ecs_content += struct_decl_cpp
        else:
            cpp_content += struct_decl_cpp
        
        hlsl_content += struct_decl_hlsl
        cs_content += struct_decl_cs

    cpp_content += ecs_content + "} // namespace Engine::ECS\n"
    cs_content += "}\n"

    with open(CPP_OUTPUT, "w") as f: f.write(cpp_content)
    with open(HLSL_OUTPUT, "w") as f: f.write(hlsl_content)
    with open(CS_OUTPUT, "w") as f: f.write(cs_content)
    print("Generated {}, {}, and {}".format(CPP_OUTPUT, HLSL_OUTPUT, CS_OUTPUT))

if __name__ == "__main__":
    generate()
